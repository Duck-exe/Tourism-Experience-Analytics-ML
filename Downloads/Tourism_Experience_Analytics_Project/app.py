def unique_values(data: pd.DataFrame, column: str) -> list[str]:
    """Return sorted, non-null string values for a Streamlit select box."""
    return sorted(data[column].dropna().astype(str).unique().tolist())


def geography_inputs(data: pd.DataFrame, prefix: str) -> tuple[str, str, str, str]:
    """Collect a *consistent* user geography from observed dataset combinations.

    The original app used four independent dropdowns. That allowed impossible
    combinations such as Asia + United States + London. Cascading filters below
    keep the selected continent, region, country, and city consistent with real
    rows in the supplied dataset, which is safer for ML inference.
    """
    geo = data[["UserContinent", "UserRegion",
                "UserCountry", "UserCityName"]].drop_duplicates()

    continent = st.selectbox(
        "User continent",
        sorted(geo["UserContinent"].dropna().astype(str).unique()),
        key=f"{prefix}_continent",
    )

    region_options = sorted(
        geo.loc[geo["UserContinent"].astype(str) == continent, "UserRegion"]
        .dropna()
        .astype(str)
        .unique()
    )
    region = st.selectbox("User region", region_options,
                          key=f"{prefix}_region")

    country_options = sorted(
        geo.loc[
            (geo["UserContinent"].astype(str) == continent)
            & (geo["UserRegion"].astype(str) == region),
            "UserCountry",
        ]
        .dropna()
        .astype(str)
        .unique()
    )
    country = st.selectbox(
        "User country", country_options, key=f"{prefix}_country")

    city_options = sorted(
        geo.loc[
            (geo["UserContinent"].astype(str) == continent)
            & (geo["UserRegion"].astype(str) == region)
            & (geo["UserCountry"].astype(str) == country),
            "UserCityName",
        ]
        .dropna()
        .astype(str)
        .unique()
    )
    city = st.selectbox("User city", city_options, key=f"{prefix}_city")

    return continent, region, country, city


def attraction_inputs(data: pd.DataFrame, prefix: str) -> tuple[str, str, str, str]:
    """Collect one historical attraction and its model feature values.

    The attraction metadata comes from the processed historical dataset so the
    exact feature names match the data used when the models were trained.
    """
    attractions = (
        data[["Attraction", "AttractionTypeLabel",
              "AttractionCityName", "AttractionCountry"]]
        .drop_duplicates("Attraction")
        .sort_values("Attraction")
    )

    name = st.selectbox(
        "Attraction",
        attractions["Attraction"].tolist(),
        key=f"{prefix}_attraction",
    )
    row = attractions.loc[attractions["Attraction"] == name].iloc[0]

    st.caption(
        "Model metadata — "
        f"Type: {row.AttractionTypeLabel} · "
        f"City label: {row.AttractionCityName} · "
        f"Country label: {row.AttractionCountry}"
    )

    return (
        str(row.Attraction),
        str(row.AttractionTypeLabel),
        str(row.AttractionCityName),
        str(row.AttractionCountry),
    )


def add_rank(result: pd.DataFrame) -> pd.DataFrame:
    """Add an explicit rank column to recommendation output."""
    ranked = result.copy().reset_index(drop=True)
    ranked.insert(0, "Rank", range(1, len(ranked) + 1))
    return ranked


def download_recommendations(result: pd.DataFrame, file_name: str, key: str) -> None:
    """Offer the displayed ranked recommendations as a CSV download."""
    st.download_button(
        "Download recommendations as CSV",
        data=result.to_csv(index=False).encode("utf-8"),
        file_name=file_name,
        mime="text/csv",
        key=key,
    )


