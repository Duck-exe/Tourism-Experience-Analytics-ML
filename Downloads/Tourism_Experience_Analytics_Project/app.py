@st.cache_data(show_spinner=False)
def load_data() -> tuple[pd.DataFrame, pd.DataFrame]:
    """Load the two processed datasets used by the application.

    Returns
    -------
    df:
        Cleaned and consolidated historical transaction dataset. It contains
        transaction, user-demographic, visit-mode, and attraction information.
    catalog:
        Cleaned expanded attraction catalog used by the recommendation system.
    """
    df = pd.read_csv(PROCESSED_DIR / "tourism_merged_clean.csv")
    catalog = pd.read_csv(PROCESSED_DIR / "attraction_catalog_clean.csv")
    return df, catalog


@st.cache_resource(show_spinner=False)
def load_models():
    """Load trained ML/recommendation artifacts once per Streamlit session."""
    classification = joblib.load(
        MODELS_DIR / "best_classification_model.joblib")
    label_encoder = joblib.load(MODELS_DIR / "visit_mode_label_encoder.joblib")
    regression = joblib.load(MODELS_DIR / "best_regression_model.joblib")
    recommender = joblib.load(MODELS_DIR / "hybrid_recommender.joblib")
    return classification, label_encoder, regression, recommender


@st.cache_data(show_spinner=False)
def load_metrics() -> tuple[dict, dict, dict]:
    """Load test/evaluation metrics produced by the training pipeline."""
    with open(METRICS_DIR / "classification_test_metrics.json", encoding="utf-8") as f:
        cls = json.load(f)

    with open(METRICS_DIR / "regression_test_metrics.json", encoding="utf-8") as f:
        reg = json.load(f)

    with open(METRICS_DIR / "recommendation_metrics.json", encoding="utf-8") as f:
        rec = json.load(f)

    return cls, reg, rec


